//! The build cache: `mur build-cache add` imports a Cargo target folder an operator built on the
//! host, and every capsule whose work folder holds the same `Cargo.lock` starts with a private
//! copy of it as `CARGO_TARGET_DIR`. Driven through the real `mur` binary on a scripted model.
//!
//! Every test runs `mur` with `HOME` set to a scratch directory under `CARGO_TARGET_TMPDIR`, never
//! under `/tmp`. The fixture project is a library whose one dependency, `dep-a`, comes from a
//! vendored directory source at one fixed absolute path outside every work folder, lent `read`
//! through `host_paths`; every command sets `CARGO_HOME` to a fresh folder under the session's
//! `$HOME` and runs `cargo --offline`, so nothing is fetched and no host Cargo configuration but
//! the ones every build reads is read.

