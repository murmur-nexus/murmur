// ── S3: no clone can corrupt or alter what another reads ──────────────────────────────

fn no_clone_alters_another_on(test: &str, containment: &str) {
    if capsule_runtime::skip_without_egress_namespace(test) {
        return;
    }
    if containment == "sealed" && !host_reaches_sealed(test) {
        return;
    }
    let Some(world) = World::new(test) else {
        return;
    };
    let world = world.contained(containment, &["sha256sum"], "");
    let clone_a = world.clone("clone-a", &lockfile(""));
    let clone_b = world.clone("clone-b", &lockfile(""));
    let warm = world.operator_build(&clone_a);
    let entry = world.add(&clone_a, &warm);
    let before = digest(&entry);
    let rlib = before
        .iter()
        .find(|(rel, _)| rel.starts_with("target/debug/deps/libdep_a-") && rel.ends_with(".rlib"))
        .map(|(rel, bytes)| (entry.join(rel), sha256_hex(bytes)))
        .expect("dep-a's rlib in the entry");
    let reflinks = reflinks_in(&world.base);

    let corrupt = "for f in \"$CARGO_TARGET_DIR\"/debug/deps/libdep_a-*.rlib; do printf junk > \"$f\" && echo \"corrupted $f\"; done";
    let plant = format!(
        "echo x > {}; echo \"exit=$?\"",
        entry.join("target/planted").display()
    );
    let overwrite = format!("printf junk > {}; echo \"exit=$?\"", rlib.0.display());
    let (output, requests) = world.run(
        Some(&clone_a),
        vec![
            bash("c1", corrupt),
            bash("c2", &plant),
            bash("c3", &overwrite),
        ],
        &[],
    );
    assert_ok(&output);
    let report = session_start(&output)["build_cache"].clone();
    assert_eq!(report["outcome"], "seeded", "{report}");
    if reflinks {
        assert!(report["reflinked"].as_u64().unwrap() > 0, "{report}");
    }
    let corrupted = result(&requests, "c1", &output);
    assert!(corrupted.contains("corrupted "), "{corrupted}");
    let refusal = if containment == "sealed" {
        "No such file or directory"
    } else {
        "Permission denied"
    };
    for id in ["c2", "c3"] {
        let text = result(&requests, id, &output);
        assert!(text.contains(refusal), "{id}: {text}");
        assert!(has_line(&text, "exit=1"), "{id}: {text}");
    }
    assert_eq!(digest(&entry), before, "the store is unchanged");

    let check = format!("sha256sum \"$CARGO_TARGET_DIR\"/debug/deps/libdep_a-*.rlib; {BUILD}");
    let (output, requests) = world.run(Some(&clone_b), vec![bash("r2", &check)], &[]);
    assert_ok(&output);
    let report = session_start(&output)["build_cache"].clone();
    if reflinks {
        assert!(report["reflinked"].as_u64().unwrap() > 0, "{report}");
    }
    let text = result(&requests, "r2", &output);
    assert!(
        text.lines().any(|line| line.trim().starts_with(&rlib.1)),
        "the seeded rlib is the entry's ({}): {text}",
        rlib.1
    );
    assert!(has_line(&text, "Fresh dep-a v0.1.0"), "{text}");
    assert_eq!(digest(&entry), before);
}

