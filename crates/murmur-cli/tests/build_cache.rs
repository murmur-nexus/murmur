/// Whether this host reaches `sealed`, printing a `[SKIP-HOST]` line when it does not.
fn host_reaches_sealed(test: &str) -> bool {
    let (decision, shortfall) =
        capsule_runtime::detect_containment_decision(murmur_artifact::ContainmentClass::Sealed);
    if decision.achieved() == murmur_artifact::ContainmentClass::Sealed {
        return true;
    }
    eprintln!(
        "[SKIP-HOST] {test}: this host cannot back sealed ({})",
        shortfall
            .map(|shortfall| shortfall.reason())
            .unwrap_or_else(|| format!("it reaches {}", decision.achieved()))
    );
    false
}

fn end_turn_response() -> String {
    json!({
        "id": "msg_end",
        "type": "message",
        "role": "assistant",
        "model": "test-model",
        "content": [{"type": "text", "text": "done"}],
        "stop_reason": "end_turn",
        "stop_sequence": null,
        "usage": {"input_tokens": 1, "output_tokens": 1},
    })
    .to_string()
}

fn bash(id: &str, command: &str) -> String {
    common::tool_use_response(id, "bash", json!({ "command": command }))
}

fn stdout(output: &Output) -> String {
    String::from_utf8_lossy(&output.stdout).into_owned()
}

fn stderr(output: &Output) -> String {
    String::from_utf8_lossy(&output.stderr).into_owned()
}

/// The text of tool call `id`'s result, which must exist.
fn result(requests: &[Value], id: &str, output: &Output) -> String {
    common::tool_result_text(requests, id)
        .unwrap_or_else(|| panic!("no tool result for {id}; stderr: {}", stderr(output)))
}

fn has_line(text: &str, line: &str) -> bool {
    text.lines().any(|candidate| candidate.trim() == line)
}

fn assert_ok(output: &Output) {
    assert!(
        output.status.success() && stdout(output).contains("status:  ok"),
        "the run must finish ok\nstdout: {}\nstderr: {}",
        stdout(output),
        stderr(output)
    );
}

fn records_dir(output: &Output) -> PathBuf {
    common::parse_records_from_stdout(&stdout(output))
}

fn trace(output: &Output) -> Vec<Value> {
    common::read_whole_trace(&records_dir(output).join("trace.jsonl"))
}

fn session_start(output: &Output) -> Value {
    trace(output)
        .into_iter()
        .find(|event| event["event_type"] == "session_start")
        .expect("session_start")
}

/// Every regular file under `dir`, relative, with its bytes.
fn digest(dir: &Path) -> Vec<(String, Vec<u8>)> {
    let mut files = Vec::new();
    let mut stack = vec![dir.to_path_buf()];
    while let Some(at) = stack.pop() {
        for entry in fs::read_dir(&at).unwrap() {
            let path = entry.unwrap().path();
            let meta = fs::symlink_metadata(&path).unwrap();
            if meta.is_dir() {
                stack.push(path);
            } else if meta.is_file() {
                files.push((
                    path.strip_prefix(dir).unwrap().display().to_string(),
                    fs::read(&path).unwrap(),
                ));
            }
        }
    }
    files.sort();
    files
}

fn sha256_hex(bytes: &[u8]) -> String {
    murmur_artifact::sha256_hex(bytes)
}

/// The vendored `dep-a` checksum `Cargo.lock` and `.cargo-checksum.json` agree on.
fn dep_a_checksum() -> String {
    sha256_hex(b"dep-a")
}

/// `Cargo.lock` for the fixture, with `extra` appended.
fn lockfile(extra: &str) -> String {
    format!(
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual \
         editing.\nversion = 4\n\n[[package]]\nname = \"dep-a\"\nversion = \"0.1.0\"\nsource = \
         \"registry+https://github.com/rust-lang/crates.io-index\"\nchecksum = \"{}\"\n\n\
         [[package]]\nname = \"fixture\"\nversion = \"0.1.0\"\ndependencies = [\n \"dep-a\",\n]\n{extra}",
        dep_a_checksum()
    )
}

/// The toolchain the host's `rustc` belongs to, or `None` (printing `[SKIP-HOST]`) without one.
fn toolchain(test: &str) -> Option<PathBuf> {
    let output = std::process::Command::new("rustc")
        .args(["--print", "sysroot"])
        .output()
        .ok()
        .filter(|output| output.status.success());
    let sysroot = output.map(|output| PathBuf::from(stdout(&output).trim()));
    let usable = sysroot.filter(|sysroot| sysroot.join("bin/cargo").is_file());
    if usable.is_none() {
        eprintln!("[SKIP-HOST] {test}: no rustc toolchain with cargo beside it");
    }
    usable
}

/// The `.cargo` folders holding a configuration file in `dir` and its ancestors: Cargo reads
/// every one of them for a project beneath `dir`, so the capsule is lent each one to see what
/// the operator's build saw.
fn ancestor_cargo_configs(dir: &Path) -> Vec<PathBuf> {
    dir.ancestors()
        .map(|ancestor| ancestor.join(".cargo"))
        .filter(|cargo| cargo.join("config.toml").is_file() || cargo.join("config").is_file())
        .collect()
}

/// Whether `dir`'s filesystem reflinks.
fn reflinks_in(dir: &Path) -> bool {
    let source = dir.join(".reflink-probe");
    fs::write(&source, b"probe").unwrap();
    let ok = std::process::Command::new("cp")
        .arg("--reflink=always")
        .arg(&source)
        .arg(dir.join(".reflink-probe-copy"))
        .status()
        .is_ok_and(|status| status.success());
    let _ = fs::remove_file(&source);
    let _ = fs::remove_file(dir.join(".reflink-probe-copy"));
    ok
}

/// A scratch `HOME`, a vendored `dep-a`, clones of the fixture project, the driver installed, and
/// the toolchain on a `PATH` of its own.
struct World {
    _root: TempDir,
    base: PathBuf,
    home: PathBuf,
    project: PathBuf,
    vendor: PathBuf,
    sysroot: PathBuf,
    path_env: String,
    /// The `capabilities:` lines beyond `network.allow`, indented two spaces.
    capabilities: String,
}

impl World {
    fn new(test: &str) -> Option<Self> {
        let sysroot = toolchain(test)?;
        let root = tempfile::tempdir_in(env!("CARGO_TARGET_TMPDIR")).unwrap();
        let base = root.path().canonicalize().unwrap();
        assert!(
            !base.starts_with("/tmp"),
            "CARGO_TARGET_TMPDIR resolves under /tmp ({}); these tests need a directory outside it",
            base.display()
        );
        let home = base.join("home");
        let project = base.join("project");
        let vendor = base.join("vendor");
        let fixture = base.join("fixture");
        for dir in [&home, &project, &fixture, &vendor.join("dep-a/src")] {
            fs::create_dir_all(dir).unwrap();
        }
        fs::write(
            vendor.join("dep-a/Cargo.toml"),
            "[package]\nname = \"dep-a\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
        )
        .unwrap();
        fs::write(
            vendor.join("dep-a/src/lib.rs"),
            "pub fn answer() -> u32 {\n    42\n}\n",
        )
        .unwrap();
        fs::write(
            vendor.join("dep-a/.cargo-checksum.json"),
            format!("{{\"files\":{{}},\"package\":\"{}\"}}", dep_a_checksum()),
        )
        .unwrap();
        let path_env = format!("{}:/usr/bin:/bin", sysroot.join("bin").display());
        let world = Self {
            _root: root,
            base,
            home,
            project,
            vendor,
            sysroot,
            path_env,
            capabilities: String::new(),
        };
        world.write_manifest("http://127.0.0.1:9");
        let driver = common::create_driver_artifact(
            &fixture,
            DRIVER,
            DRIVER_VERSION,
            &common::fixture_path("drivers/anthropic/driver/murmur-driver-anthropic.wasm"),
        );
        world
            .mur()
            .args(["install", driver.to_str().unwrap(), "--no-precompile"])
            .assert()
            .success();
        Some(world)
    }

    /// A clone of the fixture project at `<base>/<name>`, holding `lock` as its `Cargo.lock`.
    fn clone(&self, name: &str, lock: &str) -> PathBuf {
        let clone = self.base.join(name);
        fs::create_dir_all(clone.join("src")).unwrap();
        fs::create_dir_all(clone.join(".cargo")).unwrap();
        fs::write(
            clone.join("Cargo.toml"),
            "[package]\nname = \"fixture\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n\
             [dependencies]\ndep-a = \"0.1.0\"\n",
        )
        .unwrap();
        fs::write(
            clone.join("src/lib.rs"),
            "pub fn twice() -> u32 {\n    dep_a::answer() * 2\n}\n",
        )
        .unwrap();
        fs::write(
            clone.join(".cargo/config.toml"),
            format!(
                "[source.crates-io]\nreplace-with = \"vendored-sources\"\n\n\
                 [source.vendored-sources]\ndirectory = \"{}\"\n",
                self.vendor.display()
            ),
        )
        .unwrap();
        fs::write(clone.join("Cargo.lock"), lock).unwrap();
        clone
    }

    /// The operator's build: `cargo build` in `clone` on the host, with an empty `CARGO_HOME`,
    /// into `<base>/warm`, which it returns.
    fn operator_build(&self, clone: &Path) -> PathBuf {
        let warm = self.base.join("warm");
        let output = std::process::Command::new(self.sysroot.join("bin/cargo"))
            .args(["build", "--offline", "--locked", "--target-dir"])
            .arg(&warm)
            .current_dir(clone)
            .env_clear()
            .env("PATH", &self.path_env)
            .env("HOME", &self.home)
            .env("CARGO_HOME", self.base.join("operator-cargo-home"))
            .output()
            .unwrap();
        assert!(output.status.success(), "{}", stderr(&output));
        warm
    }

    fn mur(&self) -> Command {
        let mut cmd = Command::cargo_bin("mur").unwrap();
        cmd.env("HOME", &self.home)
            .env("PATH", &self.path_env)
            .env_remove("CARGO_TARGET_DIR")
            .current_dir(&self.project);
        cmd
    }

    /// `mur build-cache add` of `warm`, built from `clone`'s lockfile; returns the entry folder.
    fn add(&self, clone: &Path, warm: &Path) -> PathBuf {
        let output = self
            .mur()
            .args(["build-cache", "add", "--lockfile"])
            .arg(clone.join("Cargo.lock"))
            .arg(warm)
            .output()
            .unwrap();
        assert!(output.status.success(), "{}", stderr(&output));
        let key = sha256_hex(&fs::read(clone.join("Cargo.lock")).unwrap());
        self.store().join(key)
    }

    fn store(&self) -> PathBuf {
        self.home.join(".murmur/build-cache")
    }

    fn manifest(&self) -> PathBuf {
        self.project.join("murmur.yaml")
    }

    /// A capsule at `containment` allowed to run cargo and rustc, plus `allow`, with `extra`
    /// capabilities lines; and `~/.murmur/config.yaml` lending the toolchain, the vendored folder
    /// and every Cargo configuration above the scratch folder `read`.
    fn contained(mut self, containment: &str, allow: &[&str], extra: &str) -> Self {
        let mut binaries = vec!["bash", "cargo", "rustc"];
        binaries.extend_from_slice(allow);
        self.capabilities = format!(
            "  containment: {containment}\n  shell:\n    allow: [{}]\n{extra}",
            binaries.join(", ")
        );
        let mut lent = vec![self.sysroot.clone(), self.vendor.clone()];
        lent.extend(ancestor_cargo_configs(&self.base));
        fs::create_dir_all(self.home.join(".murmur")).unwrap();
        fs::write(
            self.home.join(".murmur/config.yaml"),
            format!(
                "host_paths:\n{}",
                lent.iter()
                    .map(|path| format!("  - path: {}\n    access: read\n", path.display()))
                    .collect::<String>()
            ),
        )
        .unwrap();
        self.write_manifest("http://127.0.0.1:9");
        self
    }

    fn write_manifest(&self, endpoint: &str) {
        fs::write(
            self.manifest(),
            format!(
                "name: {CAPSULE_NAME}\nversion: 0.0.1\nartifacts:\n  - name: {DRIVER}\n    version: \
                 {DRIVER_VERSION}\n    runtime: driver\n    gateway:\n      endpoint: {endpoint}\n      \
                 api_key: test-key\ncapabilities:\n  network:\n    allow:\n      - {endpoint}\n{}\
                 inference:\n  transport: http\n  model: test-model\n  driver:\n    artifact: {DRIVER}\n",
                self.capabilities,
            ),
        )
        .unwrap();
    }

    /// One `mur run --task` with `--workdir workdir` (none when `None`) on a model scripted with
    /// `responses` then `end_turn`.
    fn run(
        &self,
        workdir: Option<&Path>,
        responses: Vec<String>,
        env: &[(&str, &str)],
    ) -> (Output, Vec<Value>) {
        let mut responses = responses;
        responses.push(end_turn_response());
        let server = common::ScriptedServer::start(responses);
        self.write_manifest(&server.endpoint);
        let mut cmd = self.mur();
        for (key, value) in env {
            cmd.env(key, value);
        }
        cmd.args([
            "run",
            "--manifest",
            self.manifest().to_str().unwrap(),
            "--task",
            "Run each call once.",
            "--verbose",
        ]);
        if let Some(workdir) = workdir {
            cmd.arg("--workdir").arg(workdir);
        }
        let output = cmd
            .timeout(std::time::Duration::from_secs(300))
            .output()
            .unwrap();
        (output, server.requests())
    }
}

/// The command every warm-start test gives the capsule: print the variable, then build.
const BUILD: &str =
    "export CARGO_HOME=$HOME/.cargo-home; echo \"CARGO_TARGET_DIR=$CARGO_TARGET_DIR\"; cargo build -v --offline 2>&1";

/// The seed path `session_start.build_cache` names, checked against the session's records dir.
fn seed_dir(output: &Output) -> PathBuf {
    records_dir(output).join("home/.cache/cargo-target")
}

// ── S1: mur build-cache add and list ──────────────────────────────────────────────────

#[test]
fn build_cache_add_stores_an_operator_built_target_and_list_shows_it() {
    const TEST: &str = "build_cache_add_stores_an_operator_built_target_and_list_shows_it";
    let Some(world) = World::new(TEST) else {
        return;
    };
    let store = world.store();
    let list = |world: &World| {
        let output = world.mur().args(["build-cache", "list"]).output().unwrap();
        assert!(output.status.success(), "{}", stderr(&output));
        stdout(&output)
    };
    assert_eq!(
        list(&world).trim(),
        format!("no build cache entries in {}", store.display())
    );

    let clone = world.clone("clone-a", &lockfile(""));
    let warm = world.operator_build(&clone);
    let output = world
        .mur()
        .args(["build-cache", "add", "--lockfile"])
        .arg(clone.join("Cargo.lock"))
        .arg(&warm)
        .output()
        .unwrap();
    assert!(output.status.success(), "{}", stderr(&output));
    let key = sha256_hex(lockfile("").as_bytes());
    let entry = store.join(&key);
    let record: Value =
        serde_json::from_slice(&fs::read(entry.join("entry.json")).unwrap()).unwrap();
    let (files, bytes) = (
        record["files"].as_u64().unwrap(),
        record["bytes"].as_u64().unwrap(),
    );
    assert_eq!(
        stdout(&output).trim(),
        format!(
            "added {key} ({files} files, {bytes} bytes) from {}",
            warm.display()
        )
    );
    assert_eq!(record["lockfile_sha256"], json!(key));
    assert_eq!(record["source"], json!(warm.display().to_string()));
    assert!(record["added_at"].as_str().unwrap().ends_with('Z'));
    let rustc = record["rustc"]
        .as_str()
        .expect("rustc from .rustc_info.json");
    assert!(rustc.starts_with("rustc "), "{rustc}");
    let stored = digest(&entry.join("target"));
    assert_eq!(stored, digest(&warm));
    assert_eq!(files, stored.len() as u64);
    assert_eq!(
        bytes,
        stored.iter().map(|(_, b)| b.len() as u64).sum::<u64>()
    );

    // Modification times kept, owner-only modes, nothing hard-linked to the source.
    let mut stack = vec![PathBuf::new()];
    while let Some(rel) = stack.pop() {
        for item in fs::read_dir(entry.join("target").join(&rel)).unwrap() {
            let name = rel.join(item.unwrap().file_name());
            let from = fs::symlink_metadata(warm.join(&name)).unwrap();
            let to = fs::symlink_metadata(entry.join("target").join(&name)).unwrap();
            let mode = to.mode() & 0o777;
            if to.is_dir() {
                assert_eq!(mode, 0o700, "{}", name.display());
                stack.push(name);
                continue;
            }
            assert_eq!(
                to.modified().unwrap(),
                from.modified().unwrap(),
                "{}",
                name.display()
            );
            let expected = if from.mode() & 0o100 != 0 {
                0o700
            } else {
                0o600
            };
            assert_eq!(mode, expected, "{}", name.display());
            assert_eq!(to.nlink(), 1, "{}", name.display());
            assert_ne!(to.ino(), from.ino(), "{}", name.display());
        }
    }
    for dir in [&store, &entry, &entry.join("target")] {
        assert_eq!(
            fs::metadata(dir).unwrap().mode() & 0o777,
            0o700,
            "{}",
            dir.display()
        );
    }
    assert_eq!(
        fs::metadata(entry.join("entry.json")).unwrap().mode() & 0o777,
        0o600
    );

    let listed = list(&world);
    let lines: Vec<&str> = listed.lines().collect();
    assert_eq!(lines.len(), 1, "{listed}");
    assert_eq!(
        lines[0],
        format!(
            "{key}  {files} files  {bytes} bytes  {rustc}  {}  {}",
            record["added_at"].as_str().unwrap(),
            warm.display()
        )
    );

    // A second add replaces the entry whole, by rename, leaving no partial folder.
    fs::write(entry.join("target/stale"), b"x").unwrap();
    world.add(&clone, &warm);
    assert!(!entry.join("target/stale").exists());
    let names: Vec<String> = fs::read_dir(&store)
        .unwrap()
        .map(|item| item.unwrap().file_name().to_string_lossy().into_owned())
        .collect();
    assert_eq!(names, vec![key.clone()]);

    // Doctor's murmur-home audit names the store.
    let doctor = world.mur().arg("doctor").output().unwrap();
    let text = stdout(&doctor);
    let line = text
        .lines()
        .find(|line| line.trim_start().starts_with("build-cache:"))
        .unwrap_or_else(|| panic!("no build-cache line: {text}"));
    assert!(line.contains("imported Cargo build caches"), "{line}");
    assert!(
        !text.contains("something not recognised by this build"),
        "{text}"
    );
}

#[test]
fn build_cache_add_refusals_name_the_path_and_leave_the_store_unchanged() {
    const TEST: &str = "build_cache_add_refusals_name_the_path_and_leave_the_store_unchanged";
    let Some(world) = World::new(TEST) else {
        return;
    };
    let clone = world.clone("clone-a", &lockfile(""));
    let warm = world.operator_build(&clone);
    let entry = world.add(&clone, &warm);
    let before = digest(&world.store());

    let not_target = world.base.join("not-target");
    fs::create_dir_all(not_target.join("debug")).unwrap();
    let inside = world
        .home
        .join(".murmur/records/x/home/.cache/cargo-target");
    fs::create_dir_all(&inside).unwrap();
    fs::write(inside.join("CACHEDIR.TAG"), b"Signature").unwrap();
    let missing_lock = world.base.join("missing/Cargo.lock");
    for (lock, source, code, words) in [
        (
            clone.join("Cargo.lock"),
            not_target.clone(),
            "E-IO-005",
            "holds neither CACHEDIR.TAG nor .rustc_info.json".to_string(),
        ),
        (
            missing_lock.clone(),
            warm.clone(),
            "E-IO-001",
            format!("the lockfile {} does not exist", missing_lock.display()),
        ),
        (
            clone.clone(),
            warm.clone(),
            "E-IO-005",
            format!("the lockfile {} is not a regular file", clone.display()),
        ),
        (
            clone.join("Cargo.lock"),
            inside.clone(),
            "E-IO-005",
            format!(
                "{} is inside {}",
                inside.display(),
                world.home.join(".murmur").display()
            ),
        ),
    ] {
        let output = world
            .mur()
            .args(["build-cache", "add", "--lockfile"])
            .arg(&lock)
            .arg(&source)
            .output()
            .unwrap();
        let text = stderr(&output);
        assert!(!output.status.success(), "{text}");
        assert!(text.contains(&format!("error[{code}]")), "{text}");
        assert!(text.contains(&words), "{text}");
        assert_eq!(digest(&world.store()), before, "{text}");
    }
    assert!(entry.join("entry.json").is_file());
}

// ── S2, S4: a second capsule on the same lockfile starts warm ─────────────────────────

fn starts_warm_on(test: &str, containment: &str) {
    if capsule_runtime::skip_without_egress_namespace(test) {
        return;
    }
    if containment == "sealed" && !host_reaches_sealed(test) {
        return;
    }
    let Some(world) = World::new(test) else {
        return;
    };
    let world = world.contained(containment, &[], "");
    let clone_a = world.clone("clone-a", &lockfile(""));
    let clone_b = world.clone("clone-b", &lockfile(""));
    let warm = world.operator_build(&clone_a);
    let entry = world.add(&clone_a, &warm);
    let record: Value =
        serde_json::from_slice(&fs::read(entry.join("entry.json")).unwrap()).unwrap();

    let (output, requests) = world.run(Some(&clone_b), vec![bash("b1", BUILD)], &[]);
    assert_ok(&output);
    let start = session_start(&output);
    let report = &start["build_cache"];
    let seed = seed_dir(&output);
    assert_eq!(report["outcome"], "seeded", "{report}");
    assert_eq!(report["reason"], Value::Null);
    assert_eq!(report["lockfile_sha256"], record["lockfile_sha256"]);
    assert_eq!(report["entry"], json!(entry.display().to_string()));
    assert_eq!(report["target_dir"], json!(seed.display().to_string()));
    assert_eq!(report["files"], record["files"]);
    assert_eq!(report["bytes"], record["bytes"]);
    assert_eq!(
        report["reflinked"].as_u64().unwrap() + report["copied"].as_u64().unwrap(),
        report["files"].as_u64().unwrap()
    );
    assert!(report["duration_ms"].is_u64());
    assert_eq!(report["rustc"], record["rustc"]);
    assert!(start["effective_grants"].get("build_cache").is_none());

    let notice = format!(
        "build cache: seeded {} files, {} bytes from {} in {} ms ({} reflinked, {} copied); \
         CARGO_TARGET_DIR={}",
        report["files"],
        report["bytes"],
        entry.display(),
        report["duration_ms"],
        report["reflinked"],
        report["copied"],
        seed.display()
    );
    assert!(has_line(&stderr(&output), &notice), "{}", stderr(&output));

    let built = result(&requests, "b1", &output);
    assert!(
        has_line(&built, &format!("CARGO_TARGET_DIR={}", seed.display())),
        "{built}"
    );
    assert!(has_line(&built, "Fresh dep-a v0.1.0"), "{built}");
    assert!(!built.contains("Compiling dep-a"), "{built}");
    // Removed when the session ended.
    assert!(!seed.exists());

    // S4: nothing network-shaped between session_start and the first model request.
    let events = trace(&output);
    let begin = events
        .iter()
        .position(|event| event["event_type"] == "session_start")
        .unwrap();
    let first_turn = events
        .iter()
        .position(|event| {
            let kind = event["event_type"].as_str().unwrap_or_default();
            kind.starts_with("turn") || kind.starts_with("inference") || kind.starts_with("model")
        })
        .unwrap_or(events.len());
    for event in &events[begin..first_turn] {
        let kind = event["event_type"].as_str().unwrap_or_default();
        assert!(!kind.contains("network"), "{event}");
    }

    // Without the entry: no seed, no notice, no variable, a cold build.
    fs::remove_dir_all(&entry).unwrap();
    let (output, requests) = world.run(Some(&clone_a), vec![bash("a1", BUILD)], &[]);
    assert_ok(&output);
    assert_eq!(session_start(&output)["build_cache"], Value::Null);
    assert!(
        !stderr(&output).contains("build cache:"),
        "{}",
        stderr(&output)
    );
    let built = result(&requests, "a1", &output);
    assert!(has_line(&built, "CARGO_TARGET_DIR="), "{built}");
    assert!(has_line(&built, "Compiling dep-a v0.1.0"), "{built}");
}

