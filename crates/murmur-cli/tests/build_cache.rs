// ── S5: nothing changes where nothing matches ─────────────────────────────────────────

#[test]
fn nothing_changes_where_nothing_matches() {
    const TEST: &str = "nothing_changes_where_nothing_matches";
    if capsule_runtime::skip_without_egress_namespace(TEST) {
        return;
    }
    let Some(world) = World::new(TEST) else {
        return;
    };
    let world = world.contained("scoped", &[], "    baseline_env: [CARGO_TARGET_DIR]\n");
    let clone_a = world.clone("clone-a", &lockfile(""));
    let warm = world.operator_build(&clone_a);
    world.add(&clone_a, &warm);
    let differs = world.clone(
        "clone-differs",
        &lockfile("\n[[package]]\nname = \"dep-b\"\nversion = \"0.1.0\"\n"),
    );
    let no_lock = world.base.join("no-lock");
    fs::create_dir_all(&no_lock).unwrap();
    let probe = "echo \"CARGO_TARGET_DIR=${CARGO_TARGET_DIR-unset}\"; if [ -e \"$HOME/.cache/cargo-target\" ]; then echo seed-present; else echo seed-absent; fi";
    let host_value = world.base.join("host-target").display().to_string();

    for workdir in [Some(differs.as_path()), Some(no_lock.as_path()), None] {
        let (output, requests) = world.run(workdir, vec![bash("p", probe)], &[]);
        assert_ok(&output);
        assert_eq!(
            session_start(&output)["build_cache"],
            Value::Null,
            "{workdir:?}"
        );
        assert!(
            !stderr(&output).contains("build cache:"),
            "{}",
            stderr(&output)
        );
        let text = result(&requests, "p", &output);
        assert!(
            has_line(&text, "CARGO_TARGET_DIR=unset"),
            "{workdir:?}: {text}"
        );
        assert!(has_line(&text, "seed-absent"), "{workdir:?}: {text}");

        // A host value passed through `shell.baseline_env` reaches the command as before.
        let (output, requests) = world.run(
            workdir,
            vec![bash("h", probe)],
            &[("CARGO_TARGET_DIR", &host_value)],
        );
        assert_ok(&output);
        let text = result(&requests, "h", &output);
        assert!(
            has_line(&text, &format!("CARGO_TARGET_DIR={host_value}")),
            "{text}"
        );
    }

    // With a seed, the runtime's value wins over the baseline entry.
    let (output, requests) = world.run(
        Some(&clone_a),
        vec![bash("s", probe)],
        &[("CARGO_TARGET_DIR", &host_value)],
    );
    assert_ok(&output);
    let text = result(&requests, "s", &output);
    assert!(
        has_line(
            &text,
            &format!("CARGO_TARGET_DIR={}", seed_dir(&output).display())
        ),
        "{text}"
    );
    assert!(has_line(&text, "seed-present"), "{text}");
}

// ── S6: an unusable entry is reported and the run goes on cold ────────────────────────

#[test]
fn an_unusable_entry_is_reported_with_w_run_014_and_the_run_goes_on() {
    const TEST: &str = "an_unusable_entry_is_reported_with_w_run_014_and_the_run_goes_on";
    if capsule_runtime::skip_without_egress_namespace(TEST) {
        return;
    }
    let Some(world) = World::new(TEST) else {
        return;
    };
    let clone_a = world.clone("clone-a", &lockfile(""));
    let warm = world.operator_build(&clone_a);
    let entry = world.add(&clone_a, &warm);
    let record: Value =
        serde_json::from_slice(&fs::read(entry.join("entry.json")).unwrap()).unwrap();
    let bytes = record["bytes"].as_u64().unwrap();
    let clone_b = world.clone("clone-b", &lockfile(""));
    let probe = "echo \"CARGO_TARGET_DIR=${CARGO_TARGET_DIR-unset}\"; if [ -e \"$HOME/.cache\" ]; then echo cache-present; else echo cache-absent; fi";

    let check = |output: &Output, requests: &[Value], reason_has: &[String]| {
        assert_ok(output);
        let report = session_start(output)["build_cache"].clone();
        assert_eq!(report["outcome"], "skipped", "{report}");
        assert_eq!(report["target_dir"], Value::Null);
        let reason = report["reason"].as_str().unwrap().to_string();
        for words in reason_has {
            assert!(reason.contains(words.as_str()), "{reason}");
        }
        let warning = format!(
            "warning[W-RUN-014]: build cache entry {} matches this work folder's Cargo.lock but \
             was not seeded: {reason}; this run builds without it \
             (https://docs.murmur.nexus/reference/diagnostics/#w-run-014)",
            entry.display()
        );
        assert!(has_line(&stderr(output), &warning), "{}", stderr(output));
        let text = result(requests, "p", output);
        assert!(has_line(&text, "CARGO_TARGET_DIR=unset"), "{text}");
        assert!(has_line(&text, "cache-absent"), "{text}");
    };

    // Below the entry's bytes plus what the work folder holds (its sources, several hundred
    // bytes), with room for the work folder alone.
    let max = bytes + 100;
    let world = world.contained(
        "scoped",
        &[],
        &format!("  resources:\n    workdir_max_bytes: {max}\n"),
    );
    let (output, requests) = world.run(Some(&clone_b), vec![bash("p", probe)], &[]);
    check(
        &output,
        &requests,
        &[
            format!("its {bytes} bytes"),
            format!("workdir_max_bytes of {max} bytes"),
        ],
    );

    // One entry file unreadable.
    let world = world.contained("scoped", &[], "");
    let secret = digest(&entry.join("target"))
        .into_iter()
        .map(|(rel, _)| entry.join("target").join(rel))
        .find(|path| path.extension().is_some_and(|ext| ext == "rlib"))
        .unwrap();
    fs::set_permissions(&secret, fs::Permissions::from_mode(0o000)).unwrap();
    let (output, requests) = world.run(Some(&clone_b), vec![bash("p", probe)], &[]);
    fs::set_permissions(&secret, fs::Permissions::from_mode(0o600)).unwrap();
    check(
        &output,
        &requests,
        &[format!("cannot read {}", secret.display())],
    );
}

// ── S7: the seed is removed when the session ends, never through a link ───────────────

fn removed_at_session_end_on(test: &str, containment: &str) {
    if capsule_runtime::skip_without_egress_namespace(test) {
        return;
    }
    if containment == "sealed" && !host_reaches_sealed(test) {
        return;
    }
    let Some(world) = World::new(test) else {
        return;
    };
    let world = world.contained(containment, &["mv", "ln"], "");
    let clone_a = world.clone("clone-a", &lockfile(""));
    let clone_b = world.clone("clone-b", &lockfile(""));
    let warm = world.operator_build(&clone_a);
    let entry = world.add(&clone_a, &warm);
    let before = digest(&entry);
    let outside = world.base.join("outside");
    fs::create_dir_all(&outside).unwrap();
    fs::write(outside.join("canary"), b"keep").unwrap();

    let swap = format!(
        "mv \"$CARGO_TARGET_DIR/debug\" \"$CARGO_TARGET_DIR/debug-old\" && ln -s {} \"$CARGO_TARGET_DIR/debug\" && echo swapped",
        outside.display()
    );
    for (workdir, command) in [(&clone_a, swap.as_str()), (&clone_b, "echo ordinary")] {
        let (output, requests) = world.run(Some(workdir), vec![bash("x", command)], &[]);
        assert_ok(&output);
        assert_eq!(session_start(&output)["build_cache"]["outcome"], "seeded");
        let text = result(&requests, "x", &output);
        assert!(
            text.contains("swapped") || text.contains("ordinary"),
            "{text}"
        );
        let records = records_dir(&output);
        assert!(
            !records.join("home/.cache/cargo-target").exists(),
            "{command}"
        );
        assert!(fs::symlink_metadata(records.join("home/.cache/cargo-target")).is_err());
        assert!(records.join("home").is_dir());
        assert!(records.join("trace.jsonl").is_file());
        assert_eq!(fs::read(outside.join("canary")).unwrap(), b"keep");
        assert_eq!(digest(&entry), before);
    }
}

